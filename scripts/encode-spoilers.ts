// Encode the local spoilers.source.json (+ pixel art) into hooks/spoilers.ts.
//
// Usage: npm run encode               generate the file
//        npm run encode -- --check    only check that hooks/spoilers.ts matches the source
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'spoilers.source.json')
const SPRITES = join(ROOT, 'art-build', 'spoiler_sprites.json')
const SPRITES_HD = join(ROOT, 'art-build', 'spoiler_sprites_hd.json')
const PALETTES = join(ROOT, 'art-build', 'spoiler_palettes.json')
const OUT =join(ROOT, 'hooks', 'spoilers.ts')
const LINE = 96

const HEADER = `// Unlock conditions and easter-egg content are base64-encoded so they don't spoil the fun of collecting.
// This is text and numbers only: no program logic, network or file access.
// Want to peek? Call decodeSpoilers(), or paste the string into any base64 decoder.
// Generated by scripts/encode-spoilers.ts. Do not edit by hand.
`

const FOOTER = `
let raw: Spoilers | null = null
const cache: Partial<Record<Lang, Spoilers>> = {}

// The spoilers in one language (the current UI language by default), each language cached separately
export function decodeSpoilers(l: Lang = lang()): Spoilers {
  const hit = cache[l]
  if (hit) return hit
  if (raw === null) {
    const bytes = Uint8Array.from(atob(SPOILERS), c => c.charCodeAt(0))
    raw = JSON.parse(new TextDecoder().decode(bytes)) as Spoilers
  }
  const { i18n, ...base } = raw
  return (cache[l] = overlay(base, i18n?.[l]))
}
`

// Sort object keys so the same source always produces the same string
function sortDeep(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortDeep)
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value).sort().map(k => [k, sortDeep((value as Record<string, unknown>)[k])]),
    )
  }
  return value
}

function payload(): Record<string, unknown> {
  const data = JSON.parse(readFileSync(SOURCE, 'utf8')) as Record<string, unknown>
  delete data.guard
  // Without the built art this would write a spoilers.ts with no pictures in it, and --check would then call that
  // empty file correct. art-build/ is not in the public repo, so a fresh copy has none until `npm run sprites`
  const missing = [SPRITES, SPRITES_HD, PALETTES].filter(f => !existsSync(f))
  if (missing.length > 0) {
    throw new Error(`Missing ${missing.map(f => basename(f)).join(', ')} in art-build/. Run \`npm run sprites\` first (or restore art-build/ from the private backup).`)
  }
  data.sprites = JSON.parse(readFileSync(SPRITES, 'utf8'))
  data.spritesHd = JSON.parse(readFileSync(SPRITES_HD, 'utf8'))
  data.palettes = JSON.parse(readFileSync(PALETTES, 'utf8'))
  return data
}

function render(data: Record<string, unknown>): string {
  const b64 = Buffer.from(JSON.stringify(sortDeep(data)), 'utf8').toString('base64')
  const chunks: string[] = []
  for (let i = 0; i < b64.length; i += LINE) chunks.push(`"${b64.slice(i, i + LINE)}"`)
  const imports = "import { lang, overlay, type Lang } from './i18n'\nimport type { Spoilers } from './spoiler-types'\n\n"
  return HEADER + imports +`export const SPOILERS =\n  ${chunks.join(' +\n  ')}\n` + FOOTER
}

function main(argv: string[]): number {
  let rendered: string
  try {
    rendered = render(payload())
  } catch (e) {
    console.error(`✗ ${(e as Error).message}`)
    return 1
  }
  if (argv.includes('--check')) {
    const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === rendered
    console.log(same ? '✓ spoilers.ts matches the source' : '✗ spoilers.ts is stale: run npm run encode again')
    return same ? 0 : 1
  }
  writeFileSync(OUT, rendered, 'utf8')
  console.log(`Wrote hooks/spoilers.ts (${rendered.length} chars)`)
  return 0
}

process.exit(main(process.argv.slice(2)))
